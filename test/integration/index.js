'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const vscode = require('vscode');
exports.run = async function () {
  const root = vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;
  assert.ok(root, 'Requires a disposable copied project folder');
  assert.ok(path.basename(root).startsWith('keil-copy-'), 'Never test-build an original project');
  const report = {startedAt:new Date().toISOString(), steps:[]};
  const ext = vscode.extensions.getExtension('stc-workbench-local.stc-c251-workbench');
  assert.ok(ext); const api = await ext.activate(); await api.ready;
  report.steps.push('activate');
  const project = path.join(root, 'Project', 'MDK', 'SEEKFREE.uvproj');
  const imported = await vscode.commands.executeCommand('stcWorkbench.importProject', project);
  assert.equal(imported.target,'STC32G12K128'); report.steps.push('import-project');
  const rebuilt = await vscode.commands.executeCommand('stcWorkbench.rebuild');
  assert.equal(rebuilt.success,true,rebuilt.error); assert.ok(rebuilt.hex.bytes > 0);
  report.steps.push('real-keil-rebuild'); report.rebuild = rebuilt;
  const built = await vscode.commands.executeCommand('stcWorkbench.build');
  assert.equal(built.success,true,built.error); report.steps.push('real-keil-build');
  const checked = await vscode.commands.executeCommand('stcWorkbench.checkHex', rebuilt.hex.path);
  assert.equal(checked.sha256,rebuilt.hex.sha256); assert.equal(checked.flashEnabled,false);
  report.steps.push('check-built-hex');
  const blocked = await vscode.commands.executeCommand('stcWorkbench.flash');
  assert.equal(blocked.enabled,false); report.steps.push('flash-blocked');
  assert.equal(api.getState().busy,''); assert.equal(api.getState().flashEnabled,false);
  const commands = await vscode.commands.getCommands(true);
  for (const name of ['identify','selectPort','setupPython','cancel','previewHexBlocks','simulateFlash','flashSafety','showDeviceStatus']) assert.ok(commands.includes('stcWorkbench.'+name));
  report.steps.push('commands-registered'); report.completedAt = new Date().toISOString();
  await fs.writeFile(path.join(root,'integration-result.json'), JSON.stringify(report,null,2));
  console.log('STC_INTEGRATION_PASS '+report.steps.join(', '));
};
